import {chromium} from 'playwright-core';
import {spawn} from 'node:child_process';
import {mkdir,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port','4173'],{stdio:'inherit'});
let browser;
const errors=[];
try{
 for(let i=0;i<60;i++){try{if((await fetch('http://127.0.0.1:4173')).ok)break}catch{}await new Promise(r=>setTimeout(r,500))}
 browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const context=await browser.newContext({viewport:{width:900,height:420},isMobile:true,hasTouch:true,deviceScaleFactor:1});
 const page=await context.newPage();
 page.on('pageerror',e=>errors.push(String(e)));
 await page.addInitScript(()=>{Element.prototype.requestFullscreen=async()=>{};});
 await page.goto('http://127.0.0.1:4173/?qa=1');
 await page.waitForFunction(()=>window.__deadZoneQA);
 await mkdir('test-results',{recursive:true});
 await page.screenshot({path:'test-results/title.png'});
 await page.locator('#start').tap();
 await page.waitForFunction(()=>window.__deadZoneQA.state().mode==='playing');
 const state=()=>page.evaluate(()=>window.__deadZoneQA.state());
 const client=await context.newCDPSession(page);
 const box=await page.locator('#joystick').boundingBox(),fire=await page.locator('#fire').boundingBox();
 const touch=(id,x,y)=>({id,x,y,radiusX:3,radiusY:3,force:1});
 const j=touch(1,box.x+box.width/2,box.y+box.height/2),f=touch(2,fire.x+fire.width/2,fire.y+fire.height/2);
 const before=await state();
 await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[j,f]});
 await client.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{...j,x:j.x+32},f]});
 await page.waitForTimeout(650);
 await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 const moved=await state();assert.ok(moved.x>before.x+.5,'touch joystick moves');assert.ok(moved.mag<12,'simultaneous held shooting consumes rounds');
 console.log('PASS: real multi-touch movement + held fire');
 await page.locator('#reload').tap();
 await page.waitForFunction(()=>window.__deadZoneQA.state().mag===12,{},{timeout:5000});
 console.log('PASS: reload');
 await page.locator('#pause').tap();const paused=await state();await page.waitForTimeout(400);assert.equal((await state()).elapsed,paused.elapsed);
 await page.locator('#resume').tap();
 const area=await page.locator('#aimArea').boundingBox();
 await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[touch(3,area.x+20,area.y+30)]});
 await client.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[touch(3,area.x+70,area.y+30)]});
 await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 assert.notEqual((await state()).aim,moved.aim);console.log('PASS: swipe aiming, pause/resume');
 // Reset orientation then put a target on the actual firing ray.
 await page.locator('#pause').tap();await page.locator('#restart').tap();
 await page.evaluate(()=>window.__deadZoneQA.enemy(0,-3));
 const fb=await page.locator('#fire').boundingBox();
 await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[touch(4,fb.x+fb.width/2,fb.y+fb.height/2)]});
 await page.waitForFunction(()=>window.__deadZoneQA.state().kills>=1,{},{timeout:5000});
 await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 console.log('PASS: gunfire damages and kills pursuing zombie');
 await page.screenshot({path:'test-results/gameplay.png'});
 await page.evaluate(()=>{const s=window.__deadZoneQA.state();window.__deadZoneQA.prepare({health:1});window.__deadZoneQA.enemy(s.x+.1,s.z);});
 await page.waitForFunction(()=>window.__deadZoneQA.state().mode==='dead');
 assert.equal((await state()).hp,0);await page.screenshot({path:'test-results/game-over.png'});console.log('PASS: enemy damage and game over');
 await page.locator('#restart').tap();assert.equal((await state()).hp,100);assert.equal((await state()).kills,0);
 await page.waitForFunction(()=>window.__deadZoneQA.state().enemies.length>0,{},{timeout:12000});
 console.log('PASS: restart + natural spawning');
 await page.evaluate(()=>window.__deadZoneQA.prepare({time:299.95}));
 await page.waitForFunction(()=>window.__deadZoneQA.state().mode==='clear');
 await page.screenshot({path:'test-results/clear.png'});console.log('PASS: 300-second clear boundary');
 await page.setViewportSize({width:420,height:900});assert.equal(await page.locator('#rotate').isVisible(),true);console.log('PASS: portrait rotation prompt');
 assert.deepEqual(errors,[],'no page errors');
 await writeFile('test-results/report.json',JSON.stringify({passed:true,checks:['3D startup','real multi-touch movement and fire','reload','swipe aiming','pause/resume','zombie kill','enemy damage','game over','restart','natural spawning','300-second clear boundary','portrait prompt'],state:await state(),errors},null,2));
 console.log('All browser checks passed. Android hardware performance remains untested.');
}catch(error){console.error(error);process.exitCode=1;}finally{await browser?.close();server.kill('SIGTERM');}
